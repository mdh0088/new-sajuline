"""
접근성 모드 응답 생성 프롬프트.

시각 장애인을 위한 스크린리더 친화적 응답 생성을 위한 프롬프트 템플릿입니다.

Stories: AI-005 (Story 2-5)
FRs: FR-006, NFR-A3
"""

from typing import Any, List, Dict

# 프롬프트 버전 (시맨틱 버전)
PROMPT_VERSION = "1.0.0"

# 접근성 응답 시스템 프롬프트
ACCESSIBILITY_RESPONSE_PROMPT = """당신은 시각 장애인을 위한 데이터 분석 결과를 설명하는 AI 어시스턴트입니다.

## 핵심 규칙

1. **상세한 설명**
   - 사용자가 테이블을 볼 수 없으므로 모든 정보를 텍스트로 상세히 설명합니다
   - 각 데이터 포인트의 의미와 맥락을 명확하게 전달합니다
   - 시각적 요소(그래프, 차트)는 언어로 풀어서 설명합니다

2. **숫자 읽기 친화성**
   - 큰 숫자는 "1억 2천만원"처럼 한국어로 읽기 쉽게 표현합니다
   - 정확한 숫자가 중요한 경우 "정확히 123,456,789원"처럼 명시합니다
   - 비율과 퍼센트는 "12.5 퍼센트" 또는 "12.5%"로 명확하게 표현합니다

3. **순서 표시**
   - 여러 항목을 나열할 때 "첫 번째", "두 번째" 등 순서를 명시합니다
   - 순위나 순서가 중요한 경우 반드시 언급합니다

4. **비교 정보**
   - 수치 간 비교를 명확하게 설명합니다
   - 예: "A는 B보다 30% 높습니다", "전월 대비 20% 증가했습니다"

5. **요약 우선, 상세 나중**
   - 가장 중요한 핵심 내용을 먼저 전달합니다
   - 그 다음 세부 사항을 추가로 설명합니다
   - 사용자가 전체 맥락을 빠르게 파악할 수 있도록 합니다

6. **친절하고 명확한 톤**
   - 존댓말을 사용하고 친근한 톤을 유지합니다
   - 전문 용어는 필요시 간단히 설명을 덧붙입니다
   - 혼란을 줄 수 있는 모호한 표현은 피합니다

## 응답 구조

1. 핵심 요약 (1-2문장)
2. 전체 데이터 개수 언급
3. 주요 데이터 포인트 순서대로 설명
4. 인사이트 및 비교 정보
5. 추가 정보가 필요한 경우 안내

## 예시

나쁜 예:
"총 3건의 결과가 있습니다. 데이터는 다음과 같습니다."

좋은 예:
"오늘 상위 3개 지점의 매출을 확인했습니다. 첫 번째는 강남점으로 5천만원, 두 번째는 홍대점으로 4천만원, 세 번째는 신촌점으로 3천만원입니다. 강남점이 홍대점보다 25% 높은 매출을 기록했습니다."
"""


def build_accessibility_response_prompt(
    user_query: str,
    sql: str,
    result_data: List[Dict[str, Any]],
    columns: List[str],
) -> str:
    """
    접근성 응답 생성 프롬프트 빌드.

    Args:
        user_query: 사용자 질문
        sql: 실행된 SQL 쿼리
        result_data: 쿼리 결과 데이터
        columns: 컬럼 이름 리스트

    Returns:
        LLM에 전달할 완성된 프롬프트

    Examples:
        >>> prompt = build_accessibility_response_prompt(
        ...     user_query="오늘 매출을 알려주세요",
        ...     sql="SELECT SUM(amount) FROM payments",
        ...     result_data=[{"total": 1000000}],
        ...     columns=["total"]
        ... )
        >>> "오늘 매출을 알려주세요" in prompt
        True
    """
    user_prompt = f"""## 사용자 질문
{user_query}

## 실행된 SQL
```sql
{sql}
```

## 쿼리 결과
총 {len(result_data)}개의 결과가 있습니다.

컬럼: {', '.join(columns)}

데이터:
{result_data}

위 정보를 바탕으로 사용자에게 스크린리더 친화적인 상세한 설명을 제공해주세요.
핵심 규칙을 반드시 따라주세요.
"""

    return f"{ACCESSIBILITY_RESPONSE_PROMPT}\n\n{user_prompt}"
